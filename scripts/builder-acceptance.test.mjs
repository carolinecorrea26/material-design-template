// @vitest-environment node
import { afterEach, expect, it } from 'vitest';
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { createMockPlatform, totp } from './mock-platform.mjs';
import { isLibraryDraft } from '../src/domain/libraryDraft';
import { createSiteBuild } from '../src/domain/siteBuild';
import { resolvePrototypeLibrary } from '../src/domain/prototypeLibrary';
let server, dir;
afterEach(async () => { if (server) await new Promise(resolve => server.close(resolve)); if (dir) rmSync(dir, { recursive: true, force: true }); });
it('persists a real new TPA/client/Site, reopens the builder, and verifies its isolated executable snapshot and analytics', async () => {
  const read = file => JSON.parse(readFileSync(`migration-artifacts/mock/${file}.json`, 'utf8'));
  const database = read('database'), prototypeDatabase = read('prototype-data'), analyticsTags = read('analytics-tags');
  dir = mkdtempSync(join(tmpdir(), 'builder-acceptance-'));
  const otherDraft = { formatVersion: 1, siteKey: 'ama', baseRevision: 'local:v1:sha256:' + '0'.repeat(64), editVersion: 0, data: prototypeDatabase };
  writeFileSync(join(dir, 'state.json'), JSON.stringify({ version: 1, admin: null, drafts: { other: { id: 'other', version: 1, siteKey: 'ama', payload: otherDraft } }, builderDrafts: { otherBuild: { id: 'otherBuild', ownerId: 'another-user', siteKey: 'ama', libraryDraftId: 'other' } }, payments: {}, releases: {}, heads: {}, audit: [], analytics: [] }));
  server = createMockPlatform({ database, prototypeDatabase, libraryDatabase: read('library-data'), analyticsTags, statePath: join(dir, 'state.json'), validatePayload: async payload => {
    if (!isLibraryDraft(payload)) throw new Error('Invalid Library snapshot');
    resolvePrototypeLibrary(payload.data, payload.siteKey, payload.baseRevision);
  } });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const base = `http://127.0.0.1:${server.address().port}/api/mock`; let cookie = '';
  const api = async (path, body) => {
    const response = await fetch(base + path, { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-Portal-Mock': '1', Cookie: cookie }, body: JSON.stringify(body) });
    if (response.headers.get('set-cookie')) cookie = response.headers.get('set-cookie').split(';')[0];
    return { status: response.status, data: await response.json() };
  };
  const enrollment = await api('/auth/setup', { username: 'caroline', password: 'builder-test-acceptance-password' });
  await api('/auth/verify', { code: totp(enrollment.data.secret) });
  expect((await api('/library/save', { id: 'other', expectedVersion: 1, payload: otherDraft })).status).toBe(403);
  expect((await api('/library/save', { expectedVersion: 0, payload: otherDraft })).status).toBe(403);
  const source = (await api('/prototype/library', { siteKey: 'asce' })).data.payload;
  source.data.organizations = database.organizations;
  const draft = createSiteBuild(source, { siteKey: 'new-acceptance-site', siteName: 'New Acceptance Site', template: 'multi', newOrganization: true, organizationAcronym: 'TEST', organizationContact: 'Test Administrator', organizationEmail: 'admin@example.invalid', organizationPhone: '555-0100', clientAcronym: 'TESTCLIENT', clientContact: 'Client Contact', clientEmail: 'client@example.invalid', clientPhone: '555-0101', organizationKey: 'new-acceptance-tpa', organizationName: 'New Acceptance TPA', newClient: true, clientKey: 'new-acceptance-client', clientName: 'New Acceptance Client' });
  const saved = await api('/library/save', { expectedVersion: 0, payload: draft });
  expect(saved.status).toBe(200);
  const metadata = await api('/builder/draft/create', { libraryDraftId: saved.data.id, siteKey: draft.siteKey, siteName: 'New Acceptance Site', clientId: draft.data.sites.find(s => s.key === draft.siteKey).clientId });
  expect(metadata.status).toBe(200);
  const reopened = await api('/builder/drafts', {});
  expect(reopened.data).toHaveLength(2);
  expect(reopened.data.find(r => r.ownerId === 'another-user').canEdit).toBe(false);
  reopened.data = reopened.data.filter(r => r.ownerId === 'caroline');
  expect(isLibraryDraft(reopened.data[0].draftDataJson)).toBe(true);
  expect(reopened.data[0].draftDataJson.mockTransport.version).toBe(1);
  const catalog = (await api('/builder/catalog', {})).data;
  expect(catalog.organizations.some(r => r.key === 'new-acceptance-tpa')).toBe(true);
  expect(catalog.clients.some(r => r.key === 'new-acceptance-client')).toBe(true);
  const libraryCatalog = (await api('/library/catalog', { siteKey: draft.siteKey, tables: ['organizations', 'organizationProfiles', 'clients', 'sites'] })).data.data;
  expect(libraryCatalog.clients.some(c => c.acronym === 'TESTCLIENT')).toBe(true);
  expect(libraryCatalog.organizationProfiles.some(p => p.definition.support?.email === 'admin@example.invalid')).toBe(true);
  expect(libraryCatalog.organizations.some(o => o.name.startsWith('Compatibility'))).toBe(false);
  const prototype = await api('/prototype/library', { siteKey: draft.siteKey });
  expect(prototype.status).toBe(200);
  expect(resolvePrototypeLibrary(prototype.data.payload.data, draft.siteKey, prototype.data.revision).products).toHaveLength(5);
  const tag = analyticsTags.find(t => t.sites.includes('asce') && t.kind === 'page');
  expect((await api('/analytics/event', { schemaVersion: 1, tagId: tag.id, event: 'view', properties: { siteKey: draft.siteKey, template: 'multi', revision: prototype.data.revision } })).status).toBe(200);
  expect((await api('/builder/draft/update', { id: metadata.data.id, patch: { deletedAt: new Date().toISOString() } })).data.deletedAt).toBeTruthy();
  expect((await api('/builder/draft/update', { id: metadata.data.id, patch: { deletedAt: null } })).data.deletedAt).toBeNull();
  const persisted = JSON.parse(readFileSync(join(dir, 'state.json'), 'utf8'));
  expect(persisted.builderDrafts[metadata.data.id].draftDataJson).toBeUndefined();
  expect(persisted.heads).toEqual({});
});
