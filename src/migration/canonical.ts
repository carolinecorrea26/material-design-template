import { canonicalTableSpecs } from "./canonicalSchema";
import { migrationTableSpecs } from "./schema";
import { tableNames } from "../persistence/tableNames";
import { libraryMetadata, providedByTags } from "../domain/provenance";
import type { DatabaseSchema } from "../persistence/types";

export const metadataColumns = { display_id: "bigint not null unique check (display_id > 0)", provided_by: "text references public.provenance_tags(key)", source_reference: "text" };
export const expandedTableSpecs: Record<string, { columns: Record<string, string>; constraints: readonly string[] }> = {
  ...Object.fromEntries(Object.entries(migrationTableSpecs).map(([name, spec]) => [name, { ...spec, columns: { ...spec.columns, ...metadataColumns } }])),
  ...canonicalTableSpecs,
  components: { columns: { id: "text primary key", key: "text not null unique", position: "integer not null default 0", definition: "jsonb not null", ...metadataColumns }, constraints: [] },
  source_requirements: { ...canonicalTableSpecs.source_requirements, columns: { ...canonicalTableSpecs.source_requirements.columns,
    promotion_state: "text not null", promotion_reason: "text not null", active_site_keys: "jsonb not null",
  } },
};

export function canonicalSchemaSql(): string {
  const statements = ["-- Phases 1–4 only: normalized review schema. No consumer switch or legacy removal."];
  for (const [name, spec] of Object.entries(canonicalTableSpecs)) {
    statements.push(`create table public.${name} (\n${[...Object.entries(spec.columns).map(([c, t]) => `  "${c}" ${t}`), ...spec.constraints.map(c => `  ${c}`)].join(",\n")}\n);\nalter table public.${name} enable row level security;`);
  }
  statements.push(...providedByTags.map(tag => `insert into public.provenance_tags(id,key,name,display_id,provided_by,source_reference) values ('${tag}','${tag}','${tag}',${libraryMetadata("provenanceTags", tag).displayId},null,'canonical controlled vocabulary') on conflict(key) do nothing;`));
  for (const name of [...Object.keys(migrationTableSpecs), "organizations", "clients", "sites"]) {
    // Existing rows receive persisted sequence IDs; fixture imports supply deterministic IDs.
    statements.push(`alter table public.${name} add column display_id bigint generated by default as identity unique, add column provided_by text references public.provenance_tags(key), add column source_reference text;`);
  }
  statements.push(`create function public.fill_legacy_assignment_key() returns trigger language plpgsql as $$
begin
  if new.key is null then
    select s.key || '.' || (to_jsonb(new)->>TG_ARGV[0]) into new.key from public.sites s where s.id = new.site_id;
  end if;
  return new;
end $$;`);
  for (const [name, target] of [["site_coverages", "coverage_key"], ["site_products", "product_key"], ["site_riders", "rider_key"]]) {
    statements.push(`alter table public.${name} add column key text unique, add column display_id bigint generated by default as identity unique, add column provided_by text references public.provenance_tags(key), add column source_reference text;
update public.${name} a set key = s.key || '.' || a.${target} from public.sites s where a.site_id = s.id;
alter table public.${name} alter column key set not null;
create trigger ${name}_semantic_key before insert on public.${name} for each row execute function public.fill_legacy_assignment_key('${target}');`);
  }
  return statements.join("\n\n") + "\n";
}

/** Migration-only enrichment. Production seeds and consumers stay on existing sources. */
export function addLibraryMetadata(db: DatabaseSchema) {
  for (const [name, rows] of Object.entries(db)) {
    if (!(tableNames[name as keyof DatabaseSchema] in expandedTableSpecs) && !["organizations", "clients", "sites"].includes(name)) continue;
    for (const row of rows as Array<{ key: string }>) Object.assign(row, { ...libraryMetadata(name, row.key, `prototype:${name}/${row.key}`), ...row });
  }
  for (const table of ["siteCoverages", "siteProducts", "siteRiders"] as const) for (const row of db[table]) {
    const target = "productKey" in row ? row.productKey : "coverageKey" in row ? row.coverageKey : row.riderKey;
    const site = db.sites.find(s => s.id === row.siteId)!;
    const key = `${site.key}.${target}`;
    Object.assign(row, { key, ...libraryMetadata(table, key, `prototype:${table}/${key}`) });
  }
}
