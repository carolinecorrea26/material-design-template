import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import DocuSign from './DocuSign';
import PrototypeHandoffPage from '../components/feedback/PrototypeHandoffPage';
const advance = vi.fn();
vi.mock('../app/RoutePage', () => ({ default: ({ children, pageId }: { pageId: string; children: (props: object) => unknown }) => <form id={`${pageId}-form`} onSubmit={event => { event.preventDefault(); advance(); }}>{children({}) as never}</form> }));
vi.mock('../domain/prototypeLibrary', () => ({ getPrototypeLibrary: () => null }));
let root: Root, container: HTMLDivElement;
beforeEach(() => { vi.stubGlobal('IS_REACT_ACT_ENVIRONMENT', true); vi.useFakeTimers(); advance.mockClear(); container = document.createElement('div'); document.body.append(container); root = createRoot(container); });
afterEach(async () => { await act(async () => root.unmount()); container.remove(); vi.useRealTimers(); vi.unstubAllGlobals(); });
it('shows DocuSign Image TBD and advances only on an explicit click', async () => {
  await act(async () => root.render(<DocuSign />));
  expect(document.body.textContent).toContain('Image TBD');
  await act(async () => vi.advanceTimersByTime(15000));
  expect(advance).not.toHaveBeenCalled();
  expect(document.querySelector('[role="progressbar"]')).toBeNull();
  await act(async () => document.querySelector<HTMLButtonElement>('[role="dialog"] button')!.click());
  expect(advance).toHaveBeenCalledOnce();
});
it('clicks through both supplied QD images before submitting the shared page', async () => {
  const screens = [{ src: '/prototype/qd-page-1.png', alt: 'QD page 1' }, { src: '/prototype/qd-page-2.png', alt: 'QD page 2' }];
  await act(async () => root.render(<PrototypeHandoffPage pageId="health-qd" screens={screens} />));
  const dialog = () => document.querySelector('[role="dialog"]')!;
  expect(dialog().querySelector('img')?.getAttribute('src')).toBe(screens[0].src);
  await act(async () => dialog().querySelector<HTMLButtonElement>('button')!.click());
  expect(dialog().querySelector('img')?.getAttribute('src')).toBe(screens[1].src);
  expect(advance).not.toHaveBeenCalled();
  await act(async () => dialog().querySelector<HTMLButtonElement>('button')!.click());
  expect(advance).toHaveBeenCalledOnce();
});
